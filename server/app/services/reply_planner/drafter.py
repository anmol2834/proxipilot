    # =========================================================================
    # Deterministic Grounded Draft Generator (Offline / Mock / Safety Fallback)
    # =========================================================================

    def _build_deterministic_grounded_draft(
        self,
        package: MinimalEvidencePackage,
        repair_instructions: Optional[str] = None,
    ) -> StructuredReplyDraft:
        """Deterministically generates a 100% evidence-grounded draft with zero hallucination."""
        claims: List[ClaimEvidenceMapping] = []
        body_paragraphs: List[str] = []
        body_html_parts: List[str] = []

        # 1. Greeting
        body_paragraphs.append("Hello,")
        if package.is_continuation:
            if package.action_context.safe_response_strategy == "catalogue_exhausted" or not any(req.facts for req in package.requirements):
                intro_msg = "Thank you for following up. All available services in this category have already been presented."
            else:
                intro_msg = "Thank you for asking — here are additional options that weren't included in our previous message:"
            body_paragraphs.append(intro_msg)
            body_html_parts.append("<p>Hello,</p>")
            body_html_parts.append(f"<p>{intro_msg}</p>")
        else:
            body_paragraphs.append("Thank you for reaching out to us regarding your service inquiries.")
            body_html_parts.append("<p>Hello,</p>")
            body_html_parts.append("<p>Thank you for reaching out to us regarding your service inquiries.</p>")

        # Check for short contextual message ("yes", "book now", etc.)
        if package.contextual_reference and package.contextual_reference.referenced_entity_key:
            entity_key = package.contextual_reference.referenced_entity_key
            missing = package.contextual_reference.missing_parameters
            missing_str = ", ".join(missing) if missing else "your preferred scheduling details and address"
            text_p = (
                f"We have noted your interest in proceeding with service {entity_key}. "
                f"To finalize this for you, please provide {missing_str}."
            )
            body_paragraphs.append(text_p)
            body_html_parts.append(f"<p>{text_p}</p>")
            claims.append(
                ClaimEvidenceMapping(
                    claim_statement=f"Noted interest in service {entity_key} and requested required parameters {missing_str}",
                    grounding_type=GroundingType.CONTEXTUAL_ANTECEDENT,
                    is_verified=True,
                )
            )

        # 2. Iterate requirements
        for req in package.requirements:
            # A. Pricing & Product comparisons
            if req.facts:
                sku_facts: Dict[str, Dict[str, Any]] = {}
                for f in req.facts:
                    key = f.external_identity_key or f.entity_title or "Service"
                    if key not in sku_facts:
                        sku_facts[key] = {"title": f.entity_title or key, "facts": []}
                    sku_facts[key]["facts"].append(f)

                comparison_lines = []
                comparison_html_items = []
                for sku, data in sku_facts.items():
                    title = data["title"]
                    facts_list = data["facts"]
                    price_str = ""
                    for f in facts_list:
                        if f.attribute_name in ("price", "base_price", "service_price") or f.fact_type == EvidenceFactType.STRUCTURED_NUMERIC:
                            curr = "₹" if f.currency_or_unit in ("INR", "₹") else (f.currency_or_unit or "")
                            price_str = f"{curr}{f.typed_value}"
                            claims.append(
                                ClaimEvidenceMapping(
                                    claim_statement=f"{title} ({sku}) is priced at {price_str}",
                                    grounding_type=GroundingType.FACT,
                                    supported_by_fact_id=f.fact_id,
                                    supports_requirement_id=req.requirement_id,
                                    is_verified=True,
                                    numeric_values_extracted=[{
                                        "value": float(f.typed_value),
                                        "currency": f.currency_or_unit or "INR",
                                    }],
                                )
                            )

                    detail = f"• {title} ({sku}): {price_str}" if price_str else f"• {title} ({sku})"
                    comparison_lines.append(detail)
                    comparison_html_items.append(f"<li><strong>{title}</strong> ({sku}): {price_str}</li>")

                if comparison_lines:
                    intro = "Here are the verified details for the services you inquired about:"
                    body_paragraphs.append(intro)
                    body_paragraphs.extend(comparison_lines)
                    body_html_parts.append(f"<p>{intro}</p><ul>{''.join(comparison_html_items)}</ul>")

            # B. Limitations / Missing information signals
            if req.missing_signals:
                for sig in req.missing_signals:
                    limitation_text = ""
                    if sig.signal_type == MissingSignalType.CATEGORY_NOT_CONFIGURED:
                        limitation_text = (
                            "Regarding warranty and policy terms: specific policy documentation is currently "
                            "not configured in our automated knowledge base. Our team will verify and share "
                            "the official terms with you directly."
                        )
                    elif sig.signal_type == MissingSignalType.CAPABILITY_UNAVAILABLE:
                        limitation_text = (
                            "Regarding scheduling (such as Sunday service): real-time appointment booking is "
                            "not automatically confirmed at this stage. Our scheduling team will review available "
                            "technician slots and confirm with you."
                        )
                    elif sig.signal_type == MissingSignalType.NO_MATCH:
                        limitation_text = (
                            "Regarding dedicated corporate escalation contacts: no matching corporate contact "
                            "was identified for this request. Please reply here and our support team will assist you."
                        )
                    else:
                        limitation_text = f"Regarding {req.description}: {sig.reason}"

                    body_paragraphs.append(limitation_text)
                    body_html_parts.append(f"<p>{limitation_text}</p>")
                    claims.append(
                        ClaimEvidenceMapping(
                            claim_statement=limitation_text,
                            grounding_type=GroundingType.MISSING_SIGNAL,
                            supported_by_signal_id=sig.signal_id,
                            supports_requirement_id=req.requirement_id,
                            is_verified=True,
                        )
                    )

        # 3. Next step / Sign-off
        next_step = "Please let us know which service you would like to proceed with, or if you have any questions."
        closing = "Best regards,\nCustomer Support Team"
        body_paragraphs.append(next_step)
        body_paragraphs.append(closing)
        body_html_parts.append(f"<p>{next_step}</p><p>Best regards,<br>Customer Support Team</p>")

        body_text = "\n\n".join(body_paragraphs)
        body_html = "".join(body_html_parts)

        return StructuredReplyDraft(
            draft_id=f"drf_{uuid.uuid4().hex[:10]}",
            subject="Re: Your Service Inquiry & Quotation Details",
            body_text=body_text,
            body_html=body_html,
            detected_tone="professional_consultative",
            claims=claims,
            clarification_question=None,
            proposed_next_step=next_step,
            closure_detected=False,
            unconfirmed_booking_claimed=False,
            unauthorized_contact_claimed=False,
            unauthorized_policy_claimed=False,
        )

    # =========================================================================
    # Parser & Hydration
    # =========================================================================

    def _parse_structured_draft(
        self,
        data: Dict[str, Any],
        package: MinimalEvidencePackage,
    ) -> StructuredReplyDraft:
        """Parse raw OpenAI response dict into StructuredReplyDraft."""
        raw_claims = data.get("claims", [])
        parsed_claims: List[ClaimEvidenceMapping] = []

        for rc in raw_claims:
            grounding = GroundingType.FACT
            try:
                grounding = GroundingType(rc.get("grounding_type", "fact"))
            except Exception:
                pass

            is_verified = rc.get("is_verified", True)
            if grounding in (GroundingType.MISSING_SIGNAL, GroundingType.CONTEXTUAL_ANTECEDENT, GroundingType.GENERAL_COURTESY):
                is_verified = True

            parsed_claims.append(
                ClaimEvidenceMapping(
                    claim_id=f"clm_{uuid.uuid4().hex[:8]}",
                    claim_statement=rc.get("claim_statement", ""),
                    grounding_type=grounding,
                    supported_by_fact_id=rc.get("supported_by_fact_id"),
                    supported_by_signal_id=rc.get("supported_by_signal_id"),
                    supports_requirement_id=rc.get("supports_requirement_id"),
                    is_verified=is_verified,
                )
            )

        body_full = (data.get("body_text", "") + " " + data.get("body_html", "")).lower()
        booking_claimed = False
        for p in [
            r"(?<!\bno\s)(?<!\bnot\s)(?<!\bneither\s)\bbooking\s+is\s+confirmed\b",
            r"(?<!\bno\s)(?<!\bnot\s)(?<!\bneither\s)\bappointment\s+is\s+confirmed\b",
            r"\bconfirmed\s+your\s+(booking|appointment)\b",
            r"\bbooked\s+your\s+(appointment|slot)\b",
        ]:
            if re.search(p, body_full) and not re.search(r"\bno\s+(booking|appointment)\s+is\s+confirmed\b", body_full):
                booking_claimed = True
                break

        # Invariant: closure_detected is strictly valid only if customer message contains closure signals
        inbound_text = (
            (package.contextual_reference.antecedent_text if package.contextual_reference else "")
            or ""
        ).lower()
        closure_phrases = [
            "thanks, that answers my question",
            "thank you, that answers my question",
            "perfect, thank you",
            "no further questions",
            "that is all",
            "that's all",
            "got it, thanks",
            "thanks for the help",
            "no thanks",
            "not interested",
        ]
        has_closure_signal = any(p in inbound_text for p in closure_phrases)
        closure_detected = data.get("closure_detected", False) and has_closure_signal

        return StructuredReplyDraft(
            draft_id=f"drf_{uuid.uuid4().hex[:10]}",
            subject=data.get("subject", "Re: Your inquiry"),
            body_text=data.get("body_text", ""),
            body_html=(data.get("body_html") or "").strip() or _text_to_html(data.get("body_text", "")),
            detected_tone=data.get("detected_tone", "professional_consultative"),
            claims=parsed_claims,
            clarification_question=data.get("clarification_question"),
            proposed_next_step=data.get("proposed_next_step"),
            closure_detected=closure_detected,
            unconfirmed_booking_claimed=booking_claimed,
            unauthorized_contact_claimed=data.get("unauthorized_contact_claimed", False),
            unauthorized_policy_claimed=data.get("unauthorized_policy_claimed", False),
        )


