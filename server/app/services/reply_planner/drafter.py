def _text_to_html(text: str) -> str:
    """Safe, minimal HTML from the plain-text body: paragraphs, line breaks and bullet lists."""
    import html as _html

    bullet = re.compile(r"^([-*•]|\d+[.)])\s+")
    blocks = [b for b in re.split(r"\n\s*\n", (text or "").strip()) if b.strip()]
    out = []
    for b in blocks:
        lines = [ln.strip() for ln in b.split("\n") if ln.strip()]
        if lines and all(bullet.match(ln) for ln in lines):
            items = "".join(f"<li>{_html.escape(bullet.sub('', ln))}</li>" for ln in lines)
            out.append(f"<ul>{items}</ul>")
        else:
            out.append("<p>" + "<br>".join(_html.escape(ln) for ln in lines) + "</p>")
    return "".join(out)

class ReplyDrafter:
    """Enterprise Structured Reply Drafter utilizing OpenAI JSON Schema or Deterministic Fallbacks."""

    def __init__(self, settings: Optional[LlmSettings] = None):
        self._settings = settings or get_settings().llm
        self._client: Optional[AsyncOpenAI] = None
        self._global_semaphore = asyncio.Semaphore(50)
        self._tenant_semaphores: Dict[str, asyncio.Semaphore] = {}
        self._sem_lock = asyncio.Lock()

    def _get_client(self) -> AsyncOpenAI:
        if self._client is None:
            self._client = AsyncOpenAI(
                api_key=self._settings.openai_api_key or "sk-dummy-key-for-test-fallback",
                timeout=max(float(self._settings.openai_timeout_seconds), 60.0),
                max_retries=0,
            )
        return self._client

    async def _get_tenant_semaphore(self, tenant_id: str) -> asyncio.Semaphore:
        if tenant_id not in self._tenant_semaphores:
            async with self._sem_lock:
                if tenant_id not in self._tenant_semaphores:
                    self._tenant_semaphores[tenant_id] = asyncio.Semaphore(10)
        return self._tenant_semaphores[tenant_id]

    async def draft_reply(
        self,
        package: MinimalEvidencePackage,
        repair_instructions: Optional[str] = None,
        contact_context: Optional[str] = None,
        feedback_context: Optional[str] = None,
        commitment_context: Optional[str] = None,
        style_context: Optional[str] = None,
        org_context: Optional[str] = None,
        thread_context: Optional[str] = None,
        context_alerts: Optional[str] = None,
        catalogue_context: Optional[str] = None,
        customer_message: Optional[str] = None,
    ) -> Tuple[StructuredReplyDraft, Dict[str, Any]]:
        """Generate a structured reply draft grounded in the Minimal Evidence Package.

        Returns:
            Tuple of (StructuredReplyDraft, metrics_dict)
        """
        start_t = time.perf_counter()

        # 1. Check for fast-path conversational closure / simple greeting
        fast_draft = self._check_conversational_fast_path(package)
        if fast_draft is not None:
            duration_ms = (time.perf_counter() - start_t) * 1000.0
            metrics = {
                "model_used": "conversational_fast_path",
                "drafter_duration_ms": duration_ms,
                "prompt_tokens": 0,
                "completion_tokens": 0,
                "fast_path_used": True,
            }
            return fast_draft, metrics

        # 2. Check if OpenAI API key is unavailable / dummy (Mock / Test / Offline environment)
        if not self._settings.openai_api_key or self._settings.openai_api_key.startswith("sk-dummy"):
            draft = self._build_deterministic_grounded_draft(package, repair_instructions)
            duration_ms = (time.perf_counter() - start_t) * 1000.0
            metrics = {
                "model_used": "deterministic_grounded_engine",
                "drafter_duration_ms": duration_ms,
                "prompt_tokens": 0,
                "completion_tokens": 0,
                "fast_path_used": False,
            }
            return draft, metrics

        # 3. OpenAI Structured Generation Path
        client = self._get_client()
        tenant_sem = await self._get_tenant_semaphore(package.tenant_id)

        system_prompt = self._build_system_prompt()
        user_prompt = self._build_user_prompt(
            package, repair_instructions, contact_context, feedback_context, commitment_context, style_context,
            org_context, thread_context, context_alerts, catalogue_context, customer_message,
        )

        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ]

        retries = self._settings.openai_max_retries
        last_error: Optional[Exception] = None

        for attempt in range(retries + 1):
            try:
                async with self._global_semaphore:
                    async with tenant_sem:
                        call_kwargs: Dict[str, Any] = {
                            "model": self._settings.openai_model,
                            "messages": cast(Any, messages),
                            "response_format": cast(Any, {
                                "type": "json_schema",
                                "json_schema": OPENAI_REPLY_DRAFT_JSON_SCHEMA,
                            }),
                        }
                        # Fastest supported effort ("minimal" / "none"): the evidence package + rules
                        # carry the reasoning; this cut drafting latency ~2x with the same grounded output.
                        call_kwargs.update(completion_params(self._settings.openai_model, "minimal"))
                        call_kwargs["max_completion_tokens"] = 2500

                        t_api_start = time.perf_counter()
                        resp = await client.chat.completions.create(**call_kwargs)
                        api_duration_ms = (time.perf_counter() - t_api_start) * 1000.0

                choice = resp.choices[0]
                content = choice.message.content
                if not content or choice.finish_reason == "length":
                    raise ValueError(f"OpenAI draft response truncated or empty: finish_reason={choice.finish_reason}")
                data = json.loads(content)
                draft = self._parse_structured_draft(data, package)

                usage = getattr(resp, "usage", None)
                duration_ms = (time.perf_counter() - start_t) * 1000.0
                prompt_toks = usage.prompt_tokens if usage else 0
                compl_toks = usage.completion_tokens if usage else 0
                reasoning_toks = getattr(getattr(usage, "completion_tokens_details", None), "reasoning_tokens", 0) if usage else 0

                logger.info(
                    "OpenAI draft response received successfully",
                    model=self._settings.openai_model,
                    api_duration_ms=round(api_duration_ms, 2),
                    total_drafter_ms=round(duration_ms, 2),
                    prompt_tokens=prompt_toks,
                    completion_tokens=compl_toks,
                    reasoning_tokens=reasoning_toks,
                )

                metrics = {
                    "model_used": self._settings.openai_model,
                    "drafter_duration_ms": duration_ms,
                    "api_duration_ms": api_duration_ms,
                    "prompt_tokens": prompt_toks,
                    "completion_tokens": compl_toks,
                    "reasoning_tokens": reasoning_toks,
                    "fast_path_used": False,
                }
                return draft, metrics

            except Exception as err:
                last_error = err
                logger.warning(
                    "OpenAI reply drafting call failed; retrying with backoff",
                    attempt=attempt,
                    max_retries=retries,
                    error=str(err),
                )
                if attempt < retries:
                    sleep_s = (0.5 * (2 ** attempt)) + random.uniform(0.1, 0.4)
                    await asyncio.sleep(sleep_s)

        # Fallback if OpenAI API retries exhausted
        logger.error("OpenAI reply drafter exhausted retries; employing deterministic fallback", error=str(last_error))
        draft = self._build_deterministic_grounded_draft(package, repair_instructions)
        duration_ms = (time.perf_counter() - start_t) * 1000.0
        metrics = {
            "model_used": "fallback_deterministic_engine",
            "drafter_duration_ms": duration_ms,
            "prompt_tokens": 0,
            "completion_tokens": 0,
            "fast_path_used": False,
            "fallback_reason": str(last_error),
        }
        return draft, metrics

